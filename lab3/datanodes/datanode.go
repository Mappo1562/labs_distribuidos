func (s *server) FlightUpdate(ctx context.Context, in *pb.FlightStates) (*pb.Vacio, error) {
	mureloj.Lock()
	reloj[ID]++
	mureloj.Unlock()

	idx, ok := mapeo[in.UpdateType]
	if !ok {
		return nil, fmt.Errorf("tipo de update inválido: %s", in.UpdateType)
	}

	muescritura.Lock()
	defer muescritura.Unlock()

	rec, ok := bd[in.FlightId]
	if !ok {
		rec = Record{}
		rec.version = 0
		rec.Estado = ""
		rec.Puerta = ""
	}

	if idx == 0 {
		rec.Estado = in.UpdateValue
	} else {
		rec.Puerta = in.UpdateValue
	}
	rec.version++

	bd[in.FlightId] = rec
	log.Printf("FlightUpdate procesado exitosamente para FlightID: %s", in.FlightId)
	return &pb.Vacio{}, nil
}

func comparar(a [3]int, b [3]int) int {
	// devuelve: -1 si a < b, 0 si ==, 1 si a > b, 2 si concurrente
	existmenor, existmayor := false, false
	for i := 0; i < 3; i++ {
		if a[i] < b[i] {
			existmenor = true
		}
		if a[i] > b[i] {
			existmayor = true
		}
	}

	if existmenor && !existmayor {
		return -1
	}
	if existmayor && !existmenor {
		return 1
	}
	if !existmenor && !existmayor {
		return 0
	}
	return 2
}

func merge(a [3]int, b [3]int) [3]int {
	var m [3]int
	for i := 0; i < 3; i++ {
		if a[i] > b[i] {
			m[i] = a[i]
		} else {
			m[i] = b[i]
		}
	}
	return m
}

func (s *server) CoordinadorWrite(ctx context.Context, in *pb.CoordinadorWriteRequest) (*pb.CoordinadorWriteResponse, error) {
	muescritura.Lock()
	defer muescritura.Unlock()

	rec := Seat{
		FlightID: in.FlightId,
		SeatID:   in.Seat,
		Ocuppied: true,
		userID:   in.ClienteId,
	}
	bdseats[in.RequestId] = rec
	return &pb.CoordinadorWriteResponse{Success: true, Msg: "todo bien"}, nil
}

