func (s *server) FligthUpdate(ctx context.Context, in *pb.FligthStates) (*pb.Vacio, error) {
	mureloj.Lock()
	reloj[ID]++
	mureloj.Unlock()

	idx, ok := mapeo[in.UpdateType]
	if !ok {
		return nil, fmt.Errorf("tipo de update inválido: %s", in.UpdateType)
	}

	muescritura.Lock()
	defer muescritura.Unlock()

	rec, ok := bd[in.FlightId]
	if !ok {
		rec = Record{}
	}

	if idx == 0 {
		rec.Estado = in.UpdateValue
	} else {
		rec.Puerta = in.UpdateValue
	}
	bd[in.FlightId] = rec

	return &pb.Vacio{}, nil
}

func comparar(a [3]int, b [3]int) int {
	// devuelve: -1 si a < b, 0 si ==, 1 si a > b, 2 si concurrente
	existmenor, existmayor := false, false
	for i := 0; i < 3; i++ {
		if a[i] < b[i] {
			existmenor = true
		}
		if a[i] > b[i] {
			existmayor = true
		}
	}

	if existmenor && !existmayor {
		return -1
	}
	if existmayor && !existmenor {
		return 1
	}
	if !existmenor && !existmayor {
		return 0
	}
	return 2
}

func merge(a [3]int, b [3]int) [3]int {
	var m [3]int
	for i := 0; i < 3; i++ {
		if a[i] > b[i] {
			m[i] = a[i]
		} else {
			m[i] = b[i]
		}
	}
	return m
}

func (s *server) CompararRelojes(ctx context.Context, in *pb.Data) (*pb.Data, error) {
	relojRecibido := [3]int{int(in.R.R0), int(in.R.R1), int(in.R.R2)}

	muescritura.Lock()
	defer muescritura.Unlock()

	a := comparar(relojRecibido, reloj)
	if a == 0 {
		log.Printf("Comparando relojes descubri que tenemos los relojes igual")
		return &pb.Data{Flag: 0}, nil
	}
	if a == -1 { // el solicitante esta desactualizado
		log.Printf("Comparando relojes descubri que el solicitante esta desactualizado")
		datos := make([]*pb.Info, 0, len(bd))
		for k, v := range bd {
			d := &pb.Info{
				ID:     k,
				Estado: v.Estado,
				Puerta: v.Puerta,
			}
			datos = append(datos, d)

		}
		mureloj.Lock()
		reloj = merge(relojRecibido, reloj)
		r := &pb.Reloj{
			R0: int64(reloj[0]),
			R1: int64(reloj[1]),
			R2: int64(reloj[2]),
		}
		mureloj.Unlock()
		return &pb.Data{Flag: 1, Datos: datos, R: r}, nil
	}
	if a == 1 { // estoy desactualizado desactualizado
		log.Printf("Comparando relojes descubri que estoy desactualizado")
		for _, v := range in.Datos {
			bd[v.ID] = Record{
				Estado: v.Estado,
				Puerta: v.Puerta,
			}
		}

		mureloj.Lock()
		reloj = merge(relojRecibido, reloj)
		r := &pb.Reloj{
			R0: int64(reloj[0]),
			R1: int64(reloj[1]),
			R2: int64(reloj[2]),
		}
		mureloj.Unlock()

		return &pb.Data{Flag: 2, R: r}, nil

	}
	log.Printf("Comparando relojes descubri que tenemos un conflicto")
	for _, remoto := range in.Datos {
		local, existeLocal := bd[remoto.ID]
		if !existeLocal {
			bd[remoto.ID] = Record{
				Estado: remoto.Estado,
				Puerta: remoto.Puerta,
			}
			continue
		}

		// Deterministico:
		// Comparamos tuplas lexicográficamente: (Estado, Puerta)
		localTuple := local.Estado + "|" + local.Puerta
		remotoTuple := remoto.Estado + "|" + remoto.Puerta

		if remotoTuple > localTuple {
			bd[remoto.ID] = Record{
				Estado: remoto.Estado,
				Puerta: remoto.Puerta,
			}
		}
	}

	mureloj.Lock()
	reloj = merge(relojRecibido, reloj)
	r := &pb.Reloj{
		R0: int64(reloj[0]),
		R1: int64(reloj[1]),
		R2: int64(reloj[2]),
	}
	mureloj.Unlock()

	datos := make([]*pb.Info, 0, len(bd))
	for k, v := range bd {
		datos = append(datos, &pb.Info{
			ID:     k,
			Estado: v.Estado,
			Puerta: v.Puerta,
		})
	}

	return &pb.Data{Flag: 3, Datos: datos, R: r}, nil

}

