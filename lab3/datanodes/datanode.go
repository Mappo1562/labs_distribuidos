func guardarEnJSON(data *pb.FligthStates) error {
	muescritura.Lock()
	name := "db" + strconv.Itoa(ID)
	file, err := os.OpenFile(name, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	if err != nil {
		return err
	}
	defer file.Close()

	bytes, err := json.Marshal(data)
	if err != nil {
		return err
	}

	_, err = file.Write(append(bytes, '\n'))
	muescritura.Unlock()
	return err
}

func ciclo() {
	rand.Seed(int64(ID + ID*5))
	for true {
		time.Sleep(time.Duration(ID) * time.Second)
	}
}

func conect() {
	for i, conn := range conexiones {
		conn.Close()
		delete(conexiones, i)
		delete(clientes, i)
	}

	for i, dir := range AddBD {
		if i == ID {
			continue
		}

		conn, err := grpc.Dial(dir, grpc.WithTransportCredentials(insecure.NewCredentials()))
		if err != nil {
			log.Fatalf("No se pudo conectar a %v: %v", dir, err)
		}

		conexiones[i] = conn
		clientes[i] = pb.NewDatanodeClient(conn)

		log.Printf("Conectado al nodo %d en %s", i, dir)
	}
}

func runServerLoop() {
	for i := 0; i < 3; i++ { // ********************************* uso esto como criterio de termino, pero funcionara pesimo *********************************
		var err error
		lis, err = net.Listen("tcp", port)
		if err != nil {
			log.Printf("Error al escuchar en %s: %v", port, err)
			time.Sleep(2 * time.Second)
			continue
		}

		grpcServer = grpc.NewServer()
		pb.RegisterDatanodeServer(grpcServer, &server{})

		log.Printf("Nodo %d: servidor gRPC iniciado en %s", ID, port)

		err = grpcServer.Serve(lis)

		time.Sleep(5 * time.Second)
		log.Printf("******************--- reviviendo ---******************")
	}
}

func main() {

	log.Printf("Nodo %d iniciando…", ID)
	conect()
	go ciclo()
	runServerLoop()

}
