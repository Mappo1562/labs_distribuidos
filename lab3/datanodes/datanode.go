func actualizarbd(datos []*pb.Info) {
	muescritura.Lock()
	defer muescritura.Unlock()
	for _, v := range datos {
		bd[v.ID] = Record{
			Estado: v.Estado,
			Puerta: v.Puerta,
		}
	}
}

func compararRelojConElSiguiente() {
	time.Sleep(10 * time.Second)
	mureloj.Lock()
	IDsiguiente := (ID + 1) % 3
	if IDsiguiente == ID {
		IDsiguiente = (IDsiguiente + 1) % 3
	}
	log.Printf("voy a comparar mi reloj con %v", IDsiguiente)

	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	r := &pb.Reloj{
		R0: int64(reloj[0]),
		R1: int64(reloj[1]),
		R2: int64(reloj[2]),
	}
	datos := make([]*pb.Info, 0, len(bd))
	for k, v := range bd {
		datos = append(datos, &pb.Info{
			ID:     k,
			Estado: v.Estado,
			Puerta: v.Puerta,
		})
	}
	resp, err := clientes[IDsiguiente].CompararRelojes(ctx, &pb.Data{Datos: datos, R: r})
	cancel()

	if err != nil {
		log.Printf("Nodo %d no aceptó recibió compararReloj: %v", IDsiguiente, err)
		log.Printf("Probando comparar reloj con otro nodo...")
		mureloj.Unlock()
		compararRelojConElSiguiente()
		return
	}
	if resp.Flag == 1 {
		log.Printf("Estoy desactualizazo, actualizando...")
		actualizarbd(resp.Datos)
	}
	if resp.Flag == 2 {
		log.Printf("El otro nodo estaba desactualizado, le mande mi data")
	}
	if resp.Flag == 3 {
		log.Printf("Hubo conflicto, se hizo merge")
		actualizarbd(resp.Datos)
	}
	mureloj.Unlock()
}

func killNode() {
	log.Printf("******************--- simulando caída ---******************")

	grpcServer.Stop()

	if lis != nil {
		lis.Close()
	}
}

func ciclo() {
	rand.Seed(int64(ID + ID*5))
	if ID == 0 {
		time.Sleep(10 * time.Second)
		compararRelojConElSiguiente()
	}
	for true {
		time.Sleep(time.Duration(rand.Int()%5+1) * time.Second)
		if rand.Int()%100 < 1 {
			killNode()
		}
	}
}

func conect() {
	for i, conn := range conexiones {
		conn.Close()
		delete(conexiones, i)
		delete(clientes, i)
	}

	for i, dir := range AddBD {
		if i == ID {
			continue
		}

		conn, err := grpc.Dial(dir, grpc.WithTransportCredentials(insecure.NewCredentials()))
		if err != nil {
			log.Fatalf("No se pudo conectar a %v: %v", dir, err)
		}

		conexiones[i] = conn
		clientes[i] = pb.NewDatanodeClient(conn)

		log.Printf("Conectado al nodo %d en %s", i, dir)
	}
}

func runServerLoop() {
	for i := 0; i < 3; i++ { // ********************************* uso esto como criterio de termino, pero funcionara pesimo *********************************
		var err error
		lis, err = net.Listen("tcp", port)
		if err != nil {
			log.Printf("Error al escuchar en %s: %v", port, err)
			time.Sleep(2 * time.Second)
			continue
		}

		grpcServer = grpc.NewServer()
		pb.RegisterDatanodeServer(grpcServer, &server{})

		log.Printf("Nodo %d: servidor gRPC iniciado en %s", ID, port)

		err = grpcServer.Serve(lis)

		time.Sleep(5 * time.Second)
		log.Printf("******************--- reviviendo ---******************")
	}
}

func main() {

	log.Printf("Nodo %d iniciando…", ID)
	conect()
	go ciclo()
	runServerLoop()

}
