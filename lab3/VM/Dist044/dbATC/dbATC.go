func killNode() {
	log.Printf("******************--- simulando caída ---******************")

	grpcServer.Stop()

	mulider.Lock()
	lider = -1
	mulider.Unlock()

	if lis != nil {
		lis.Close()
	}
}

func conect() {
	for i, conn := range conexiones {
		conn.Close()
		delete(conexiones, i)
		delete(clientes, i)
	}

	for i, dir := range AddBD {
		if i == ID {
			continue
		}

		conn, err := grpc.Dial(dir, grpc.WithTransportCredentials(insecure.NewCredentials()))
		if err != nil {
			log.Fatalf("No se pudo conectar a %v: %v", dir, err)
		}

		conexiones[i] = conn
		clientes[i] = pb.NewATCClient(conn)

		log.Printf("Conectado al nodo ATC %d en %s", i, dir)
	}
}

func runServerLoop() {
	for i := 0; i < 3; i++ { // ********************************* uso esto como criterio de termino, pero funcionara pesimo *********************************
		var err error
		lis, err = net.Listen("tcp", port)
		if err != nil {
			log.Printf("Error al escuchar en %s: %v", port, err)
			time.Sleep(2 * time.Second)
			continue
		}

		grpcServer = grpc.NewServer()
		pb.RegisterATCServer(grpcServer, &server{})

		log.Printf("Nodo ATC %d: servidor gRPC iniciado en %s", ID, port)

		err = grpcServer.Serve(lis)

		time.Sleep(5 * time.Second)
		mulider.Lock()
		lider = -1
		mulider.Unlock()
		log.Printf("******************--- reviviendo ---******************")
	}
	log.Printf("Nodo ATC %d: terminando ejecución", ID)
	os.Exit(0)
}

func main() {

	log.Printf("Nodo ATC %d iniciando…", ID)
	conect()
	go ciclo()
	runServerLoop()

}
