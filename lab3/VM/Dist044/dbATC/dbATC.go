func leerHistorico() ([]*pb.Record, error) {
	name := "db" + strconv.Itoa(ID)

	f, err := os.Open(name)
	if err != nil {
		if os.IsNotExist(err) {
			return []*pb.Record{}, nil
		}
		return nil, err
	}
	defer f.Close()

	scanner := bufio.NewScanner(f)
	var records []*pb.Record

	for scanner.Scan() {
		line := scanner.Bytes()
		var r pb.Record
		if err := json.Unmarshal(line, &r); err != nil {
			log.Printf("Error leyendo línea del histórico: %v", err)
			continue
		}
		// copiar a un nuevo puntero
		rec := r
		records = append(records, &rec)
	}

	if err := scanner.Err(); err != nil {
		return nil, err
	}

	return records, nil
}

// ************************************************ LA IMPLEMENTACIÓN DE CONSENSO NO SOPORTA MUCHAS LLAMADAS SEGUIDAS ************************************************
func consenso() {
	time.Sleep(2 * time.Second) // ********************************* tiempo para que los otros llamen a INSERTLIDER *********************************
	muVotos.Lock()
	votosCopy := make(map[int]*pb.Record)
	for k, v := range votos {
		votosCopy[k] = v
	}
	votos = make(map[int]*pb.Record)
	muVotos.Unlock()
	final := decidirRecord(votosCopy)
	if final == nil {
		log.Printf("No hubo consenso válido")
		return
	}
	log.Printf("concenso exitoso pista: %v, vuelo: %v", final.Pista, final.FlightId)
	for i, cliente := range clientes {
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
		_, err := cliente.ResultadoConsenso(ctx, final)
		cancel()
		if err != nil {
			log.Printf("Error al mandar el resultado del consenso a %v", err)
		} else {
			log.Printf("Valor guardado correctamente por %v", i)
		}
	}

	muinsert.Lock()
	if guardarEnJSON(final) != nil {
		log.Fatalf("Error al guardar el resultado consensuado")
	}
	muinsert.Unlock()
}

func decidirRecord(votos map[int]*pb.Record) *pb.Record {

	ids := make([]int, 0, len(votos))
	for id := range votos {
		ids = append(ids, id)
	}

	for i := 0; i < len(ids); i++ {
		a := votos[ids[i]]
		if a == nil {
			continue
		}
		for j := i + 1; j < len(ids); j++ {
			b := votos[ids[j]]
			if b == nil {
				continue
			}
			if proto.Equal(a, b) {
				return a
			}
		}
	}

	return nil
}

