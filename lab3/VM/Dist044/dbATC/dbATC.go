func guardarEnJSON(data *pb.Record) error {
	log.Printf("************************ Guardando en JSON: FlightID=%s, Pista=%d ***********************", data.FlightId, data.Pista)
	name := "data/db" + strconv.Itoa(ID)
	file, err := os.OpenFile(name, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	if err != nil {
		return err
	}
	defer file.Close()

	bytes, err := json.Marshal(data)
	if err != nil {
		return err
	}

	_, err = file.Write(append(bytes, '\n'))
	return err
}

func aplicarHistorico(records []*pb.Record) error {
	name := "db" + strconv.Itoa(ID)
	tmp := name + ".tmp"

	f, err := os.Create(tmp)
	if err != nil {
		return err
	}

	for _, r := range records {
		b, err := json.Marshal(r)
		if err != nil {
			f.Close()
			return err
		}
		if _, err := f.Write(append(b, '\n')); err != nil {
			f.Close()
			return err
		}
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(tmp, name)
}

func conseguirvotosLider() (int, []int64) {
	aceptados := 1
	respuestas := make([]int64, 0)

	for i, cliente := range clientes {
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
		resp, err := cliente.PostularALider(ctx, &pb.Postulante{Id: int64(ID)})
		cancel()

		if err != nil {
			log.Printf("Nodo ATC %d no respondió a PostularALider, esta muerto", i)
			continue
		}

		respuestas = append(respuestas, resp.Id)
		if resp.Id == int64(ID) {
			aceptados++
		}
	}
	return aceptados, respuestas
}

func NotificarNuevoLider() {
	for i, cliente := range clientes {
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
		resp, err := cliente.InformarNewLider(ctx, &pb.Postulante{Id: int64(ID)})
		cancel()

		if err != nil {
			log.Printf("Nodo ATC %d no aceptó notificación: %v", i, err)
		} else {
			log.Printf("Nodo ATC %d confirmó nuevo líder (%d)", i, resp.Id)
		}
	}

	mulider.Lock()
	lider = ID
	mulider.Unlock()

	log.Printf("Ahora soy el líder")
}

func pedirHistoricoAlLiderYGuardarlo(liderCopy int) {
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()
	clienteLider, ok := clientes[liderCopy]
	if !ok {
		log.Printf("No puedo contactar al lider para restaurar la bd")
		return
	}
	historicos, err := clienteLider.GetHistorico(ctx, &pb.Vacio{})
	if err != nil {
		log.Printf("No puedo llamar a la funcion del lider para restaurar la bd")
		return
	}
	muinsert.Lock()
	if err := aplicarHistorico(historicos.Records); err != nil {
		log.Printf("No logre guardar el historico correctamente")
		return
	}
	muinsert.Unlock()
	log.Printf("historico guardado correctamente")
}

func verLider() {
	mulider.Lock()
	liderCopy := lider
	mulider.Unlock()

	if liderCopy != -1 {
		log.Printf("El lider actual es %v", liderCopy)
		return
	}

	log.Printf("Postularé a lider")

	aceptados, respuestas := conseguirvotosLider()

	// si tengo mayoría, paso a ser lider
	if aceptados > 1 {
		log.Printf("Fui aceptado como líder, notificando...")
		NotificarNuevoLider()
		return
	} else { // si no, significa que hay otro lider y que revivi
		if len(respuestas) == 0 {
			log.Printf("Estaba muerto y revivi pero nadie respondió a la postulación, terminaré aquí")
			log.Printf("Nodo ATC %d: terminando ejecución", ID)
			os.Exit(0)
			return
		}
		log.Printf("Estaba muerto y revivi y ya existe un lider, estableciendo como lider al actual: %v", respuestas[0])
		// actualizar lider
		mulider.Lock()
		lider = int(respuestas[0])
		liderCopy := lider
		mulider.Unlock()
		log.Printf("Pidiendo el historico al lider")
		pedirHistoricoAlLiderYGuardarlo(liderCopy)
		return
	}
}

func revisarLiderVivo() {
	mulider.Lock()
	liderActual := lider
	mulider.Unlock()

	if liderActual == -1 {
		return
	}
	if liderActual == ID {
		log.Printf("comenzando el conteo para mi muerte XoX")
		time.Sleep(20 * time.Second)
		killNode()
		return
	}

	clienteLider, ok := clientes[liderActual]
	if !ok {
		log.Printf("No existe cliente para el lider %d. Marcando lider como muerto. T_T", liderActual)
		mulider.Lock()
		lider = -1
		mulider.Unlock()
		return
	}

	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()

	_, err := clienteLider.Ping(ctx, &pb.Vacio{})
	if err != nil {
		log.Printf("El lider %d no responde. Esta muerto? D:", liderActual)
		mulider.Lock()
		lider = -1
		mulider.Unlock()
		return
	}

	log.Printf("Lider %d sigue vivo, larga vida al lider!!", liderActual)
}

func ciclo() {
	time.Sleep(5 * time.Second)
	rand.Seed(int64(ID + ID*5))
	for true {
		time.Sleep(time.Duration(rand.Intn(5)+1) * time.Second)
		verLider()
		revisarLiderVivo()
	}
}

