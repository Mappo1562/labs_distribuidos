type server struct {
	pb.UnimplementedATCServer
}

func init() {
	ID, _ = strconv.Atoi(os.Getenv("ID"))
	port = AddBD[ID][6:]
	name := "data/db" + strconv.Itoa(ID)
	file, err := os.Create(name)
	if err != nil {
		panic(err)
	}
	defer file.Close()
}

