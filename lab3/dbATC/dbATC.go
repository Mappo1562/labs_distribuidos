func (s *server) PostularALider(ctx context.Context, in *pb.Postulante) (*pb.NewLider, error) {
	mulider.Lock()
	if lider == -1 {
		lider = int(in.Id)
		mulider.Unlock()
		return &pb.NewLider{Id: int64(lider)}, nil
	}
	mulider.Unlock()
	return &pb.NewLider{Id: int64(lider)}, nil
}

func (s *server) InformarNewLider(ctx context.Context, in *pb.Postulante) (*pb.NewLider, error) {
	mulider.Lock()
	lider = int(in.Id)
	mulider.Unlock()
	return &pb.NewLider{Id: int64(lider)}, nil
}

func revisarLiderVivo() {
	mulider.Lock()
	liderActual := lider
	mulider.Unlock()

	if liderActual == -1 {
		return
	}
	if liderActual == ID {
		return
	}

	clienteLider, ok := clientes[liderActual]
	if !ok {
		log.Printf("No existe cliente para el lider %d. Marcando lider como muerto. T_T", liderActual)
		mulider.Lock()
		lider = -1
		mulider.Unlock()
		return
	}

	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()

	_, err := clienteLider.Ping(ctx, &pb.Vacio{})
	if err != nil {
		log.Printf("El lider %d NO responde. Esta muerto? D:", liderActual)
		mulider.Lock()
		lider = -1
		mulider.Unlock()
		return
	}

	log.Printf("Lider %d sigue vivo, larga vida al lider!!", liderActual)
}

func (s *server) Ping(ctx context.Context, in *pb.Vacio) (*pb.Vacio, error) {
	mulider.Lock()
	liderc := lider
	mulider.Unlock()
	if liderc == ID {
		return &pb.Vacio{}, nil
	}
	return &pb.Vacio{}, fmt.Errorf("ya no soy el lider :c")
}

func ciclo() {
	rand.Seed(ID + ID*5)
	for true {
		time.Sleep(time.Duration(rand.Intn(5)+1) * time.Second)
		verLider()
		revisarLiderVivo()
	}
}

func main() {

	lis, err := net.Listen("tcp", port)
	if err != nil {
		log.Fatalf("conexión fallida:\n %v", err)
	}

	grpcServer := grpc.NewServer()
	pb.RegisterNodoBDConsensoServer(grpcServer, &server{})
	log.Println("Nodo con consenso activo en el puerto ", port)

	go func() { //////////////////////////////////////////////////////// Criterio de termino
		time.Sleep(60 * time.Second)
		log.Println("Tiempo cumplido. Deteniendo servidor...")
		grpcServer.GracefulStop()
	}()

	time.Sleep(5 * time.Second)
	for i, dir := range AddBD {
		if i == ID {
			continue
		}

		conn, err := grpc.Dial(dir, grpc.WithTransportCredentials(insecure.NewCredentials()))
		if err != nil {
			log.Fatalf("No se pudo conectar a %v: %v", dir, err)
		}

		conexiones[i] = conn
		clientes[i] = pb.NewNodoBDConsensoClient(conn)

		log.Printf("Conectado al nodo %d en %s", i, dir)
	}

	go ciclo()

	if err := grpcServer.Serve(lis); err != nil {
		log.Fatalf("conexión fallida:\n %v", err)
	}

}
