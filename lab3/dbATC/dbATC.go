const (
	ID         = 0 // la idea es que sea 0 para el nodo 1, 1 para el 2 y asi
	PortNodo1  = "db1ATC:50051"
	PortNodo2  = "db2ATC:50052"
	PortNodo3  = "db3ATC:50053"
	PortBroker = "broker:50050"
)

var (
	AddBD      = [3]string{PortNodo1, PortNodo2, PortNodo3}
	BD         = []string{}
	port       string
	mulider    sync.Mutex
	muinsert   sync.Mutex
	lider      = -1
	clientes   = make(map[int]pb.NodoBDConsensoClient)
	conexiones = make(map[int]*grpc.ClientConn)
	votos      = make(map[int]*pb.Record)
	muVotos    sync.Mutex
)

type server struct {
	pb.UnimplementedNodoBDConsensoServer
}

func init() {
	AddBD[ID] = AddBD[ID][6:]
	log.Printf("AddBD[ID] = %s\n", AddBD[ID])
	port = AddBD[ID]
}

func (s *server) INSERT(ctx context.Context, in *pb.Record) (*pb.InsertResponse, error) {
	mulider.Lock() // quiza estos candados no sean necesarios
	liderCopy := lider
	mulider.Unlock()
	if liderCopy != ID {
		clienteLider, ok := clientes[liderCopy]
		if !ok {
			return nil, fmt.Errorf("no puedo contactar al líder")
		}
		_, err := clienteLider.INSERTLIDER(ctx, &pb.RecordID{R: in, Id: ID})
		if err != nil {
			return nil, err
		}

		return &pb.InsertResponse{Id: ID, Lider: false}, nil
	}
	// hacer la pega de lider
	muVotos.Lock()
	votos[int(ID)] = in
	muVotos.Unlock()
	concenso() // ************************************************ FALTA UN IF PARA VER SI EL CONCENSO ESTUVO BIEN O NO ************************************************
	return &pb.InsertResponse{Id: ID, Lider: false}, nil
}

func (s *server) INSERTLIDER(ctx context.Context, in *pb.RecordID) (*pb.Vacio, error) {
	muVotos.Lock()
	votos[int(in.Id)] = in.R
	muVotos.Unlock()
	return &pb.Vacio{}, nil
}

// ************************************************ LA IMPLEMENTACIÓN DE CONSENSO NO SOPORTA MUCHAS LLAMADAS SEGUIDAS ************************************************
func consenso() {
	time.Sleep(1 * time.Second) // tiempo para que los otros llamen a INSERTLIDER
	muVotos.Lock()
	votosCopy := make(map[int]*pb.Record)
	for k, v := range votos {
		votosCopy[k] = v
	}
	votos = make(map[int]*pb.Record) // limpiar para el siguiente insert
	muVotos.Unlock()
	final := decidirRecord(votosCopy)
}

func decidirRecord(votos map[int]*pb.Record, liderID int) *pb.Record {
	// 1) buscar cualquier par igual (dos iguales -> ganar)
	ids := make([]int, 0, len(votos))
	for id := range votos {
		ids = append(ids, id)
	}

	for i := 0; i < len(ids); i++ {
		a := votos[ids[i]]
		if a == nil {
			continue
		}
		for j := i + 1; j < len(ids); j++ {
			b := votos[ids[j]]
			if b == nil {
				continue
			}
			if proto.Equal(a, b) { // ************************************************ HAY Q SACAR UNA FUNCION PARA COMPARAR DOS RECORD ************************************************
				// Hay mayoría (2 iguales) → devolver ese registro
				return a
			}
		}
	}

	return nil
}

