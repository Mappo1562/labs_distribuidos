func initConsumidores() {
	file, err := os.Open("consumidores.csv")
	if err != nil {
		log.Fatalf("No se pudo abrir el archivo de filtros para consumidores: %v", err)
		return
	}
	defer file.Close()

	reader := csv.NewReader(file)
	reader.Comma = ','

	rows, err := reader.ReadAll()
	if err != nil {
		log.Fatalf("No se pudo leer el archivo de filtros para consumidores: %v", err)
		return
	}

	consumidores = make(map[string][]string)
	nGrupo := 0
	var puertoInt int
	for i, row := range rows {
		if i == 0 {
			continue
		}
		id := row[0]
		categorias := row[1]
		tiendas := row[2]
		precio := row[3]

		if nGrupo != int(id[1])-48 {
			nGrupo = int(id[1]) - 48
			puertoInt = 60050 + 10*nGrupo
		}
		puertoInt = puertoInt + 1
		direccion := "grupo" + strconv.Itoa(nGrupo) + ":" + strconv.Itoa(puertoInt)
		// Guardamos en el map
		consumidores[id] = []string{direccion, categorias, tiendas, precio}
		log.Printf("agregado uno con direccion %v", direccion)
	}
}

