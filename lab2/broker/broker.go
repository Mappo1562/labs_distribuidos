const (
	port  = ":50050"
	addn1 = "localhost:50051"
	addn2 = "localhost:50052"
	addn3 = "localhost:50053"
)

type server struct {
	pb.UnimplementedBrokerServer
}

var (
	registrados map[string]int32 // map[nombre] = rol
	mapeoRoles  = map[int]string{
		0: "Productor",
		1: "Consumidor",
		2: "nodo BD",
	}
)

func (s *server) Registrarse(ctx context.Context, in *pb.Registro) (*pb.Bool, error) {
	_, ok := registrados[in.Nombre]
	if ok {
		log.Printf("Entidad %s ya registrada, error.", in.Nombre)
		err := fmt.Errorf("No se pudo registrar la entidad en el broker, ya estaba registrada.\n")
		return &pb.Bool{Flag: false}, err
	}
	registrados[in.Nombre] = in.Rol
	log.Printf("Entidad %s registrada correctamente.", in.Nombre)
	return &pb.Bool{Flag: true}, nil
}

func GenerarOfertaHelp(in *pb.Oferta, dir string) bool {
	conn, err := grpc.Dial(dir, grpc.WithInsecure())
	if err != nil {
		log.Printf("[°] no se pudo conectar con %v \nerror: %v", dir, err)
		return false
	}
	defer conn.Close()
	client := pb.NewNodeServiceClient(conn)

	ctx, cancel := context.WithTimeout(context.Background(), time.Second*10)
	defer cancel()

	response, err := client.GuardarOferta(ctx, in)
	if err != nil {
		log.Printf("No se pudo guardar correctamente la oferta por el nodo %v\nerror: %v", dir, err)
		return false
	}
	if response != nil && response.Flag {
		log.Printf("Oferta guardada correctamente por el nodo %v", dir)
		return true
	}

	log.Printf("No se pudo guardar correctamente la oferta por el nodo %v", dir)
	return false
}

func (s *server) GenerarOferta(ctx context.Context, in *pb.Oferta) (*pb.Bool, error) {
	flag := true
	var mugenof sync.Mutex
	rol, ok := registrados[in.Tienda]
	if !ok || rol != 0 {
		log.Printf("La tienda %v no está registrada en el broker. Oferta rechazada.", in.Tienda)
		return &pb.Bool{Flag: false}, nil
	}

	publicado := [3]int{0, 0, 0}
	for flag {
		var wg sync.WaitGroup
		wg.Add(3)

		// conexión nodo 1
		mugenof.Lock()
		if publicado[0] == 0 {
			go func() {
				defer wg.Done()
				if GenerarOfertaHelp(in, addn1) {
					mugenof.Lock()
					publicado[0] = 1
					mugenof.Unlock()
				}
			}()
		}
		mugenof.Unlock()

		// conexión nodo 2
		mugenof.Lock()
		if publicado[1] == 0 {
			go func() {
				defer wg.Done()
				if GenerarOfertaHelp(in, addn2) {
					mugenof.Lock()
					publicado[1] = 1
					mugenof.Unlock()
				}
			}()
		}
		mugenof.Unlock()

		// conexión nodo 3
		mugenof.Lock()
		if publicado[2] == 0 {
			go func() {
				defer wg.Done()
				if GenerarOfertaHelp(in, addn3) {
					mugenof.Lock()
					publicado[2] = 1
					mugenof.Unlock()
				}
			}()
		}
		mugenof.Unlock()
		wg.Wait()

		if publicado[0]+publicado[1]+publicado[2] > 1 {
			log.Printf("**** Oferta de %v, proveniente de la tienda %v guardada correctamente por dos o mas nodos ****", in.Producto, in.Tienda)
			flag = false
		} else {
			log.Printf("No se pudo guardar correctamente la oferta proveniente de %v. Intentando nuevamente", in.Tienda)
		}
	}
	return &pb.Bool{Flag: true}, nil
}

